// Regenerates src/vulndb.js from the retire.js repository (https://github.com/RetireJS/retire.js,
// Apache License 2.0). Run before a release to pick up new advisories:
//
//   node tools/update-vulndb.mjs                 # downloads repository/jsrepository.json from GitHub
//   node tools/update-vulndb.mjs path/to/jsrepository.json
//
// Only what the extension uses is kept: the file-content, URL and file-name version extractors and,
// per advisory, the affected range, severity, identifiers, a short summary and one reference link.
import { readFile, writeFile } from 'node:fs/promises';

const SOURCE = 'https://raw.githubusercontent.com/RetireJS/retire.js/master/repository/jsrepository.json';
const OUT = new URL('../src/vulndb.js', import.meta.url);
const SKIP = new Set(['retire-example', 'dont check']);
const SEV = { low: 'low', medium: 'medium', high: 'high', critical: 'critical' };
const MAX_SUMMARY = 220;

const arg = process.argv[2];
const text = arg ? await readFile(arg, 'utf8') : await (await fetch(SOURCE)).text();
const repo = JSON.parse(text);

const valid = (re) => {
  try {
    new RegExp(re.replace(/§§version§§/g, '[0-9][0-9.a-z_\\-]+'));
    return true;
  } catch {
    return false;
  }
};
const clean = (s) => String(s || '').replace(/\s+/g, ' ').trim();
const short = (s) => (s.length > MAX_SUMMARY ? s.slice(0, MAX_SUMMARY - 1).trimEnd() + '…' : s);

const libs = [];
let advisories = 0;
let dropped = 0;
for (const [name, lib] of Object.entries(repo)) {
  if (SKIP.has(name) || !lib?.vulnerabilities) continue;
  const x = lib.extractors || {};
  const pick = (list) => (list || []).filter((re) => (valid(re) ? true : (dropped++, false)));
  const content = pick(x.filecontent);
  const uri = pick(x.uri);
  const file = pick(x.filename);
  if (!content.length && !uri.length && !file.length) continue;
  const vulns = [];
  for (const v of lib.vulnerabilities) {
    if (!v.below) continue;
    const ids = v.identifiers || {};
    const refs = [...(ids.CVE || []), ...(ids.githubID ? [ids.githubID] : []), ...(ids.osvdb || []).map((o) => 'OSVDB-' + o)];
    vulns.push([
      v.atOrAbove || '',
      v.below,
      SEV[v.severity] || 'medium',
      refs,
      short(clean(ids.summary || (ids.bug ? 'bug ' + ids.bug : ids.issue ? 'issue ' + ids.issue : ''))),
      (v.info || []).find((u) => /^https?:\/\//.test(u)) || '',
    ]);
  }
  if (!vulns.length) continue;
  advisories += vulns.length;
  libs.push({ name, npm: lib.npmname || '', content, uri, file, vulns });
}
libs.sort((a, b) => a.name.localeCompare(b.name));

const header = `// GENERATED by tools/update-vulndb.mjs from the retire.js repository — do not edit by hand.
// Source: https://github.com/RetireJS/retire.js (repository/jsrepository.json), Apache License 2.0;
// see vulndb-LICENSE.md. Regenerate with: node tools/update-vulndb.mjs
//
// Per library: version extractors (§§version§§ marks the version) for the file content, the URL and
// the file name, and advisories as [atOrAbove, below, severity, ids, summary, link].
`;
const body = `export const VULNDB_DATE = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n\nexport const VULNDB = ${JSON.stringify(libs, null, 0)
  .replace(/\},\{"name"/g, '},\n{"name"')
  .replace(/^\[/, '[\n')
  .replace(/\]$/, ',\n];')}\n`;
await writeFile(OUT, header + '\n' + body);
console.log(`${libs.length} libraries, ${advisories} advisories${dropped ? `, ${dropped} extractors dropped (invalid in JS)` : ''} → src/vulndb.js`);
