// OpenAPI 3.0 and Postman v2.1 exports, for proxies and API tools:
//   Burp Suite: Professional API scans import OpenAPI; in Community, the OpenAPI Parser BApp loads it into the site map
//   Caido: the ReDocs community plugin imports OpenAPI 3.x and Postman v2.1 collections into Replay
//   Also ZAP (OpenAPI add-on), Postman and Insomnia.
// Pure: no chrome.* APIs, so it can be unit-tested with Node.
//
// Input model (built by the popup from the findings):
//   { host, origin,
//     endpoints: [{ method, path, tags }]            HTTP API rows; path relative, absolute or `${BASE}/…`
//     bodyFields: { "POST /api/x": ["a", "b"] }      runtime-captured request body fields per endpoint
//     headers: ["X-Tenant-Id", …]                    custom request headers (code, CORS, observed traffic)
//     bearer: true                                   an "Authorization: Bearer …" header was seen
//     graphql: { endpoint, operations: [{ kind, name, document }] } }

const WRITE = new Set(['POST', 'PUT', 'PATCH', 'DELETE']);

/** "/api/users/:id/x?a=&b=" or "${API}/v1/x" or "https://h/p" → { origin, path: "/api/users/{id}/x", query: ["a","b"] } */
export function splitEndpoint(raw, origin) {
  let s = String(raw).trim();
  let base = origin;
  let templated = false;
  const t = /^\$\{[^}]+\}/.exec(s);
  if (t) {
    s = s.slice(t[0].length);
    templated = true;
  }
  const abs = /^(?:(https?):)?\/\/([^/?#]+)(.*)$/i.exec(s);
  if (abs) {
    base = `${abs[1] || 'https'}://${abs[2]}`;
    s = abs[3] || '/';
  }
  const [pathPart, queryPart = ''] = s.split('#')[0].split('?');
  let path = (pathPart.startsWith('/') ? pathPart : '/' + pathPart)
    .replace(/\$\{([\w$.]+)\}/g, (_, n) => `{${n.split('.').pop()}}`)
    .replace(/\/:([A-Za-z_]\w*)/g, '/{$1}')
    .replace(/\/{2,}/g, '/');
  if (path.length > 1) path = path.replace(/\/$/, '');
  const query = [...new Set(queryPart.split('&').map((p) => decodeURIComponent(p.split('=')[0] || '')).filter((n) => /^[\w.[\]-]{1,60}$/.test(n)))];
  return { origin: base, path, query, templated };
}

const pathParams = (path) => [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);

function operationId(method, path, used) {
  let id = (method.toLowerCase() + path.replace(/\{([^}]+)\}/g, 'By_$1').replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''))).slice(0, 100);
  let n = id;
  for (let i = 2; used.has(n); i++) n = id + i;
  used.add(n);
  return n;
}

/** OpenAPI 3.0.3 document (object). */
export function buildOpenApi(model) {
  const headers = [...new Set(model.headers || [])].filter((h) => !/^authorization$/i.test(h)).slice(0, 30);
  const doc = {
    openapi: '3.0.3',
    info: {
      title: `${model.host} (JS Recon)`,
      version: new Date().toISOString().slice(0, 10),
      description:
        'Generated by JS Recon from client-side code and observed traffic. Paths, methods and parameter names are what the client uses; types and responses are not known.',
    },
    servers: [{ url: model.origin }],
    paths: {},
    components: { parameters: {}, securitySchemes: {} },
  };
  for (const h of headers) {
    doc.components.parameters[`header_${h.replace(/[^\w]/g, '_')}`] = { name: h, in: 'header', required: false, schema: { type: 'string' } };
  }
  if (model.bearer) {
    doc.components.securitySchemes.bearerAuth = { type: 'http', scheme: 'bearer' };
    doc.security = [{ bearerAuth: [] }];
  }
  const used = new Set();
  const add = (method, path, op, origin) => {
    const item = (doc.paths[path] ||= {});
    if (origin && origin !== model.origin) item.servers = [{ url: origin }];
    const m = method.toLowerCase();
    if (item[m]) {
      // same path + method seen with other query names: merge parameters
      const known = new Set(item[m].parameters.map((p) => `${p.in}:${p.name}`));
      for (const p of op.parameters) if (!known.has(`${p.in}:${p.name}`)) item[m].parameters.push(p);
      return;
    }
    item[m] = op;
  };
  for (const e of model.endpoints || []) {
    const method = String(e.method || 'GET').toUpperCase();
    if (!/^(?:GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)$/.test(method)) continue;
    const { origin, path, query, templated } = splitEndpoint(e.path, model.origin);
    const parameters = [
      ...pathParams(path).map((name) => ({ name, in: 'path', required: true, schema: { type: 'string' } })),
      ...query.map((name) => ({ name, in: 'query', required: false, schema: { type: 'string' } })),
      ...headers.map((h) => ({ $ref: `#/components/parameters/header_${h.replace(/[^\w]/g, '_')}` })),
    ];
    const op = {
      operationId: operationId(method, path, used),
      summary: `${method} ${path}`,
      parameters,
      responses: { default: { description: 'Not known (discovered in client-side code)' } },
    };
    const tags = (e.tags || []).filter((t) => ['observed', 'runtime', 'interesting', 'write'].includes(t));
    if (tags.length) op['x-jsrecon-tags'] = tags;
    if (templated) op['x-jsrecon-note'] = 'The client prefixes this path with a base URL variable';
    const fields = model.bodyFields?.[`${method} ${path}`];
    if (WRITE.has(method) && method !== 'DELETE') {
      const properties = Object.fromEntries((fields || []).map((f) => [f, { type: 'string' }]));
      op.requestBody = { required: false, content: { 'application/json': { schema: { type: 'object', properties } } } };
    }
    add(method, path, op, origin);
  }
  const g = model.graphql;
  if (g?.operations?.length) {
    const { origin, path } = splitEndpoint(g.endpoint || '/graphql', model.origin);
    const examples = {};
    for (const o of g.operations) examples[`${o.kind}_${o.name}`.slice(0, 80)] = { summary: `${o.kind} ${o.name}`, value: { operationName: o.name, query: o.document, variables: {} } };
    add(
      'POST',
      path,
      {
        operationId: operationId('POST', path, used),
        summary: `GraphQL (${g.operations.length} operations)`,
        parameters: headers.map((h) => ({ $ref: `#/components/parameters/header_${h.replace(/[^\w]/g, '_')}` })),
        requestBody: { required: true, content: { 'application/json': { schema: { type: 'object', properties: { operationName: { type: 'string' }, query: { type: 'string' }, variables: { type: 'object' } } }, examples } } },
        responses: { default: { description: 'GraphQL response' } },
      },
      origin,
    );
  }
  if (!Object.keys(doc.components.securitySchemes).length) delete doc.components.securitySchemes;
  return doc;
}

/** Postman Collection v2.1 (object). Path parameters become :name, the base URL is {{baseUrl}}. */
export function buildPostman(model) {
  const headers = [...new Set(model.headers || [])].filter((h) => !/^authorization$/i.test(h)).slice(0, 30);
  const header = headers.map((key) => ({ key, value: '', disabled: true }));
  const item = [];
  const urlOf = (origin, path, query) => {
    const base = origin === model.origin ? '{{baseUrl}}' : origin;
    const segs = path.split('/').filter(Boolean).map((s) => s.replace(/^\{([^}]+)\}$/, ':$1'));
    const q = query.map((key) => ({ key, value: '' }));
    return {
      raw: `${base}/${segs.join('/')}${q.length ? '?' + q.map((x) => `${x.key}=`).join('&') : ''}`,
      host: [base],
      path: segs,
      ...(q.length ? { query: q } : {}),
      ...(pathParams(path).length ? { variable: pathParams(path).map((key) => ({ key, value: '' })) } : {}),
    };
  };
  const seen = new Set();
  for (const e of model.endpoints || []) {
    const method = String(e.method || 'GET').toUpperCase();
    if (!/^(?:GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)$/.test(method)) continue;
    const { origin, path, query } = splitEndpoint(e.path, model.origin);
    const key = `${method} ${origin} ${path}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const request = { method, header, url: urlOf(origin, path, query) };
    if (WRITE.has(method) && method !== 'DELETE') {
      const fields = model.bodyFields?.[`${method} ${path}`] || [];
      request.body = { mode: 'raw', raw: JSON.stringify(Object.fromEntries(fields.map((f) => [f, ''])), null, 2), options: { raw: { language: 'json' } } };
    }
    item.push({ name: `${method} ${path}`, request });
  }
  const g = model.graphql;
  if (g?.operations?.length) {
    const { origin, path } = splitEndpoint(g.endpoint || '/graphql', model.origin);
    item.push({
      name: 'GraphQL',
      item: g.operations.map((o) => ({
        name: `${o.kind} ${o.name}`,
        request: { method: 'POST', header, url: urlOf(origin, path, []), body: { mode: 'graphql', graphql: { query: o.document, variables: '{}' } } },
      })),
    });
  }
  const collection = {
    info: { name: `${model.host} (JS Recon)`, schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json', description: 'Endpoints discovered by JS Recon in client-side code and observed traffic.' },
    item,
    variable: [{ key: 'baseUrl', value: model.origin }],
  };
  if (model.bearer) collection.auth = { type: 'bearer', bearer: [{ key: 'token', value: '{{token}}', type: 'string' }] };
  return collection;
}

// ── "send to proxy": GET requests for concrete, harmless-looking URLs ──

const UNSAFE_PATH_RE =
  /log-?out|sign-?out|sign_out|delete|remove|destroy|purge|drop|wipe|clear|reset|revoke|cancel|unsubscribe|deactivate|disable|terminate|kill|shutdown|restart|reboot|rollback|uninstall/i;

/**
 * URLs safe enough to request with GET so they appear in an intercepting proxy's site map:
 * same site as the host, no placeholders, nothing that sounds like it changes state.
 */
export function replayCandidates(urls, siteOf, host) {
  const site = siteOf(String(host).replace(/:\d+$/, ''));
  const out = [];
  const skipped = { unsafe: 0, template: 0, offsite: 0 };
  for (const raw of new Set(urls)) {
    let u;
    try {
      u = new URL(raw);
    } catch {
      continue;
    }
    if (!/^https?:$/.test(u.protocol)) continue;
    if (/\{[^}]*\}|\$\{|\/:[A-Za-z_]/.test(decodeURI(u.pathname)) || /\{|\$\{/.test(u.search)) {
      skipped.template++;
      continue;
    }
    if (siteOf(u.hostname) !== site) {
      skipped.offsite++;
      continue;
    }
    if (UNSAFE_PATH_RE.test(u.pathname + u.search)) {
      skipped.unsafe++;
      continue;
    }
    out.push(u.href);
  }
  return { urls: out, skipped };
}
